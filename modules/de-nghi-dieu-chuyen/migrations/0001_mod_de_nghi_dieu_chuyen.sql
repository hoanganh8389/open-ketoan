CREATE TABLE phieu (
  id                  bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint        NOT NULL,
  doc_no              text          NOT NULL,
  doc_date            date          NOT NULL,
  branch_code         text          NOT NULL,
  warehouse_code      text          NOT NULL DEFAULT '',
  to_branch_code      text          NOT NULL,
  to_branch_name      text          NOT NULL DEFAULT '',
  partner_code        text,
  partner_name        text,
  reason_code         text,
  staff_name          text          NOT NULL DEFAULT '',
  note                text          NOT NULL DEFAULT '',
  lines               jsonb         NOT NULL DEFAULT '[]'::jsonb,
  total_items         integer       NOT NULL DEFAULT 0,
  total_qty           numeric(18,4) NOT NULL DEFAULT 0,
  status              text          NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'converted', 'rejected', 'cancelled')),
  row_version         integer       NOT NULL DEFAULT 1,
  source              text          NOT NULL DEFAULT 'ketoan' CHECK (source IN ('ketoan', 'pos')),
  intent              jsonb,
  transfer            jsonb,
  reject_reason       text,
  cancel_reason       text,
  decided_by          text,
  decided_by_name     text,
  decided_at          timestamptz,
  created_by          text          NOT NULL,
  created_by_name     text          NOT NULL DEFAULT '',
  created_at          timestamptz   NOT NULL DEFAULT now(),
  updated_by          text          NOT NULL,
  updated_at          timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, doc_no)
);
CREATE INDEX phieu_ngay ON phieu (tenant_id, doc_date DESC, id DESC);
CREATE INDEX phieu_chi_nhanh ON phieu (tenant_id, branch_code, status);
CREATE INDEX phieu_chi_nhanh_nhan ON phieu (tenant_id, to_branch_code, status);
